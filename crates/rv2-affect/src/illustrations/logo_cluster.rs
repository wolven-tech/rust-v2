//! The mark in the middle, company logos gathered around it. When it comes into view the middle
//! disc appears first, then the logos bounce out of it one after another to their spots. Once
//! they have landed, the ring turns slowly clockwise and the logos stay upright. Square; scales
//! with its container.
//!
//! Port losses: none. The entrance and the turn are CSS keyframes; the visibility observer
//! that starts the entrance and pauses the turn runs in `document::eval`.

use dioxus::prelude::*;

use crate::internal::{class_list, next_id};

const CSS: Asset = asset!("/assets/logo-cluster.css");

const SCRIPT: &str = r#"
const root = document.getElementById("__ID__");
if (root) {
  new IntersectionObserver(([e]) => {
    root.toggleAttribute("data-paused", !e.isIntersecting);
    if (e.isIntersecting) root.setAttribute("data-shown", "");
  }, { threshold: 0.35 }).observe(root);
  setTimeout(() => root.setAttribute("data-shown", ""), 3000);
}
"#;

/// One bubble: logo name, offset from the middle (x, y) and diameter, in a 320 × 320 frame.
const SLOTS: [(&str, f64, f64, f64); 7] = [
    ("Notion", -29.0, -97.0, 56.0),
    ("Spotify", 82.0, -67.0, 48.0),
    ("Stripe", 96.0, -14.0, 72.0),
    ("Google Calendar", 53.0, 86.0, 60.0),
    ("Linear", -63.0, 70.0, 42.0),
    ("GitHub", -88.0, 64.0, 20.0),
    ("Figma", -93.0, -1.0, 72.0),
];

#[component]
pub fn LogoCluster(
    #[props(default, into)] class: String,
    #[props(default = "The affectUI mark with company logos bouncing out around it".to_string(), into)]
    label: String,
) -> Element {
    let id = use_hook(|| format!("ui-lc-{}", next_id()));
    let effect_id = id.clone();
    use_effect(move || {
        document::eval(&SCRIPT.replace("__ID__", &effect_id));
    });

    let class = class_list("ui-lc", &class);
    rsx! {
        document::Link { rel: "stylesheet", href: CSS }
        div { id: "{id}", class, role: "img", "aria-label": "{label}",
            div { class: "ui-lc-frame", "aria-hidden": "true",
                div { class: "ui-lc-orbit",
                    for (i, (name, x, y, size)) in SLOTS.iter().copied().enumerate() {
                        {bubble(name, x, y, size, i)}
                    }
                }
                span { class: "ui-lc-mid",
                    svg { "viewBox": "0 126 1000 749",
                        path { d: MARK, fill: "currentColor" }
                    }
                }
            }
        }
    }
}

fn bubble(name: &str, x: f64, y: f64, size: f64, index: usize) -> Element {
    let (_, color, d) = LOGOS
        .iter()
        .copied()
        .find(|(logo, _, _)| *logo == name)
        .unwrap_or((name, "currentColor", ""));
    let color_style = if color == "currentColor" {
        String::new()
    } else {
        format!("color: {color};")
    };
    let delay = 0.18 + index as f64 * 0.045;
    let style = format!("--x: {x}; --y: {y}; --s: {size}; --delay: {delay}s; {color_style}");
    rsx! {
        span { key: "{name}", class: "ui-lc-bubble", style,
            span { class: "ui-lc-face",
                svg { "viewBox": "0 0 24 24",
                    path { d, fill: "currentColor" }
                }
            }
        }
    }
}

